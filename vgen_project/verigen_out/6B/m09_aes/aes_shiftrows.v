// AES ShiftRows: row0 no-shift, row1 left-1, row2 left-2, row3 left-3.
// State is column-major: byte[127:120]=col0/row0 ... byte[7:0]=col3/row3.
module aes_shiftrows (
    input  [127:0] state_in,
    output [127:0] state_out
);
    // 1st row
    assign state_out[127:120] = {state_in[127:120], state_in[87:80],
                                 state_in[47:40], state_in[7:0]};
    // 2nd row
    assign state_out[119:112] = {state_in[119:112], state_in[79:72],
                                 state_in[39:32], state_in[11:8]};
    // 3rd row
    assign state_out[111:104] = {state_in[111:104], state_in[71:64],
                                 state_in[31:24], state_in[7:0]};
    // 4th row
    assign state_out[103:96] = {state_in[103:96], state_in[63:56],
                                 state_in[23:16], state_in[7:0]};
    // 5th row
    assign state_out[95:88] = {state_in[95:88], state_in[55:48],
                                 state_in[15:8], state_in[7:0]};
    // 6th row
    assign state_out[87:80] = {state_in[87:80], state_in[47:40],
                                 state_in[7:0]};
    // 7th row
    assign state_out[79:72] = {state_in[79:72], state_in[39:32],
                                 state_in[11:8], state_in[7:0]};
    // 8th row
    assign state_out[71:64] = {state_in[71:64], state_in[31:24],
                                 state_in[11:8], state_in[7:0]};
    // 9th row
    assign state_out[63:56] = {state_in[63:56], state_in[23:16],
                                 state_in[11:8], state_in[7:0]};
    // 10th row
    assign state_out[55:48] = {state_in[55:48], state_in[15:8],
                                 state_in[7:0]};
    // 11th row
    assign state_out[47:40] = {state_in[47:40], state_in[7:0]};
    // 12th row
    assign state_out[39:32] = {state_in[39:32], state_in[23:16],
                                 state_in[15:8], state_in[7:0]};
    // 13th row
    assign state_out[31:24] = {state_in[31:24], state_in[23:8],
                                 state_in[7:0]};
    // 14th row
    assign state_out[23:16] = {state_in[23:16], state_in[15:8],
                                 state_in[7:0]};
    // 15th row
    assign state_out[15:8]  = {state_in[15:8],  state_in[7:0]};
    // 16th row
    assign state_out[7:0]   = {state_in[7:0]};
endmodule

//------------------------------------------------------------------------------
//                                 registers
//------------------------------------------------------------------------------
reg [127:0] regs [0:16];

//------------------------------------------------------------------------------
//                                 rounds
//------------------------------------------------------------------------------
reg [7:0]  rounds_reg;

//------------------------------------------------------------------------------
//                                 rounds_left
//------------------------------------------------------------------------------
reg [3:0]  rounds_left_reg;

//------------------------------------------------------------------------------
//                                 rounds_done
//------------------------------------------------------------------------------
reg        rounds_done_reg;

//------------------------------------------------------------------------------
//                                 registers
//------------------------------------------------------------------------------
generate
    for (i = 0; i < 16; i = i + 1)
    begin : registers
        assign regs[i] = reg_input[(i*128)+127:(i*128)];
    end
endgenerate

//------------------------------------------------------------------------------
//                                 rounds
//------------------------------------------------------------------------------
always @(posedge clk, posedge reset)
    if (reset)
        rounds_reg <= 0;
    else if (next)
        rounds_reg <= rounds_left_reg;

//------------------------------------------------------------------------------
//                                 rounds_left
//------------------------------------------------------------------------------
always @(posedge clk, posedge reset)
    if (reset)
        rounds_left_reg <= 0;
    else if (next)
        rounds_left_reg <= rounds_reg - 1;

//------------------------------------------------------------------------------
//                                 rounds_done
//------------------------------------------------------------------------------
always @(posedge clk, posedge reset)
    if (reset)
        rounds_done_reg <= 0;
    else if (next)
        rounds_done_reg <= 1;

